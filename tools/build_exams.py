#!/usr/bin/env python3
"""Convert data/exams/exam-*.json into js/exams.js for the site.

Run from the project root:  python3 tools/build_exams.py

Accepts both source shapes:
  options: ["A) text", "B) text", ...]   or   options: {"A": "text", "B": "text", ...}
  correct_answer: "B"                    or   correct_answers: ["A", "C"]
Exam titles come from the file number (exam-3.json -> "Practice Exam 3"), because
the source files' own titles are not unique.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "exams"
OUT = ROOT / "js" / "exams.js"
PREFIX = re.compile(r"^\s*([A-Z])\)\s*")


def options_of(q):
    raw = q["options"]
    if isinstance(raw, dict):
        letters = sorted(raw)
        return letters, [str(raw[k]).strip() for k in letters]
    letters, texts = [], []
    for i, opt in enumerate(raw):
        m = PREFIX.match(opt)
        letters.append(m.group(1) if m else chr(65 + i))
        texts.append(PREFIX.sub("", opt).strip())
    return letters, texts


def convert(path):
    data = json.loads(path.read_text(encoding="utf-8"))
    n = int(re.search(r"(\d+)", path.stem).group(1))
    questions, errors = [], []
    for q in data["questions"]:
        letters, texts = options_of(q)
        answers = q.get("correct_answers") or [q.get("correct_answer")]
        try:
            idx = sorted(letters.index(a) for a in answers)
        except ValueError:
            errors.append(f"{path.name} Q{q.get('number')}: answer {answers} not in {letters}")
            continue
        questions.append({"q": q["question"].strip(), "options": texts, "answer": idx,
                          "explain": q.get("explanation", "").strip()})
    return {"id": n, "title": f"Practice Exam {n}", "questions": questions}, errors


def main():
    files = sorted(SRC.glob("exam-*.json"), key=lambda p: int(re.search(r"(\d+)", p.stem).group(1)))
    exams, errors = [], []
    for f in files:
        exam, errs = convert(f)
        exams.append(exam)
        errors += errs
    if errors:
        sys.exit("\n".join(errors))
    OUT.write_text(
        "/* Generated by tools/build_exams.py from data/exams/*.json. Do not edit by hand. */\n"
        f"window.CCDV_EXAMS = {json.dumps(exams, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    for e in exams:
        multi = sum(len(q["answer"]) > 1 for q in e["questions"])
        print(f"{e['title']}: {len(e['questions'])} questions ({multi} multiple-response)")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
